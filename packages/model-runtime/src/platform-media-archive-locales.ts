export function formatPlatformMediaArchiveError(messageKey: string, params: Readonly<Record<string, string | number | boolean | null>> = {}, locale = 'en'): string | undefined {
  if (!messageKey.startsWith('platform_media.archive.')) return undefined;
  const key = messageKey.slice('platform_media.archive.'.length);
  const row = Object.hasOwn(PLATFORM_MEDIA_ARCHIVE_MESSAGES, key) ? PLATFORM_MEDIA_ARCHIVE_MESSAGES[key] : undefined;
  if (!row) return undefined;
  const index = LOCALES.indexOf(locale as typeof LOCALES[number]);
  return row[index < 0 ? 0 : index]!.replace(/\{(\w+)\}/g, (_match, name: string) => Object.hasOwn(params, name) ? String(params[name] ?? '') : '');
}
