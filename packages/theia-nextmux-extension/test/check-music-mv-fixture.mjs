import assert from 'node:assert/strict';
import { mkdir, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
const desktopRequire = createRequire(new URL('../../../apps/desktop/package.json', import.meta.url));
const puppeteer = desktopRequire('puppeteer-core');
const url = process.argv[2];
if (!url?.startsWith('http://127.0.0.1:')) throw new Error('Provide an isolated local MV fixture URL');
const output = process.argv[3] || join(tmpdir(), 'nextmux-mv-ui');
await mkdir(output, { recursive: true });
const profile = await mkdtemp(join(tmpdir(), 'nextmux-mv-ui-profile-'));
const browser = await puppeteer.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', userDataDir: profile, args: ['--autoplay-policy=no-user-gesture-required'] });
const results = [];
try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1280, height: 900 });
    await page.goto(url, { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.nmx-music-mv');
    const clickText = text => page.evaluate(value => { const button = [...document.querySelectorAll('button')].find(item => item.textContent.trim() === value); if (!button) throw new Error('Missing button: ' + value); button.click(); }, text);
    const receipt = () => page.$eval('[data-fixture-receipt]', node => node.getAttribute('data-fixture-receipt'));
    await clickText('一键生成 AI 分段');
    await page.waitForSelector('[role=alertdialog]');
    assert.equal(await receipt(), '');
    assert.match(await page.$eval('[role=alertdialog]', node => node.textContent), /Synthetic Cinema 1/);
    await page.screenshot({ path: join(output, 'music-mv-confirmation.png'), fullPage: true });
    await clickText('确认并开始生成');
    assert.match(await receipt(), /^generated:segment-1:true$/);
    results.push('Model/count/cost are reviewed before the only generation callback');
    await clickText('一键生成 AI 分段');
    await page.waitForSelector('[role=alertdialog]');
    await page.click('[data-fixture-change-model]');
    await page.waitForFunction(() => !document.querySelector('[role=alertdialog]'));
    results.push('A changed model/quote invalidates the open confirmation');
    await page.$eval('.nmx-music-mv-lines li:nth-child(2) .nmx-music-mv-nudge button:last-child', node => node.click());
    assert.match(await receipt(), /^nudge:line-2:100$/);
    results.push('Per-line +0.1 s control invokes the millisecond edit callback');
    await clickText('播放并打拍');
    await page.waitForFunction(() => !document.querySelector('audio').paused);
    await page.$eval('audio', node => { node.currentTime = 2.25; });
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelector('[data-fixture-receipt]').getAttribute('data-fixture-receipt').startsWith('tap:line-1:'));
    const tapped = await receipt();
    const at = Number(tapped.split(':').pop());
    assert.ok(at >= 2_250 && at < 4_000, tapped);
    await page.$eval('.nmx-music-mv', node => node.dispatchEvent(new KeyboardEvent('keydown', { key: ' ', repeat: true, bubbles: true })));
    assert.equal(await receipt(), tapped);
    const field = await page.$('.nmx-music-mv-segment textarea');
    await field.focus();
    await page.keyboard.press('Space');
    assert.equal(await receipt(), tapped);
    results.push('Space stamps the current audio time; held Space and editable fields do not stamp');
    await clickText('结束打拍');
    await page.$eval('audio', node => { node.pause(); node.currentTime = 16; });
    await page.waitForFunction(() => !!document.querySelector('.nmx-music-mv-frame img'));
    assert.match(await page.$eval('.nmx-music-mv-subtitle', node => node.textContent), /让晚风带走等待/);
    results.push('Seeking changes both the visual source and current lyric from the audio clock');
    await page.screenshot({ path: join(output, 'music-mv-structure.png'), fullPage: true });
    await page.select('.nmx-music-mv-segment select', 'upload-image');
    await clickText('选择文件');
    assert.match(await receipt(), /^import:segment-1$/);
    results.push('Changing visual source exposes the matching upload callback');
    await page.goto(`${url}?locale=ar`, { waitUntil: 'domcontentloaded' });
    assert.equal(await page.$eval('main', node => node.dir), 'rtl');
    assert.match(await page.$eval('.nmx-music-mv-heading', node => node.textContent), /فيديو موسيقي/);
    results.push('Arabic labels and RTL direction render from the same component');
    console.log(JSON.stringify({ passed: results.length, failed: 0, results, output, profile }, null, 2));
} finally { await browser.close(); }
