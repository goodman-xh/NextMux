import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
import { createCanvasDocument, validateCanvasDocument } from '@nextmux/comic-core/canvas';
const source = await readFile(new URL('../src/browser/nextmux-canvas-story.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { splitCanvasStory, parseCanvasStoryPlan, appendCanvasStoryChunk } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const now = '2026-10-03T22:00:00Z';
test('story chunks cover the exact source, preserve Unicode, and stay bounded', () => {
    const story = ('夜晚。阿月推开门。🌙\n'.repeat(2000));
    const chunks = splitCanvasStory(story, 511);
    assert.equal(chunks.join(''), story);
    assert.ok(chunks.every(chunk => chunk.length <= 511 && !/[\uD800-\uDBFF]$/.test(chunk)));
    assert.throws(() => splitCanvasStory(story, 200));
});
test('planning refuses malformed, empty or unbounded results before applying nodes', () => {
    assert.throws(() => parseCanvasStoryPlan('{"shots":[],"characters":[]}'));
    assert.throws(() => parseCanvasStoryPlan('{"shots":[null],"characters":[]}'));
    assert.throws(() => parseCanvasStoryPlan(JSON.stringify({characters:[],shots:Array(41).fill({title:'x',prompt:'y',characters:[]})})));
});
test('successive chunks form one horizontal sequence, reuse identity and do not mutate prior versions', () => {
    const canvas = createCanvasDocument({id:'board',projectId:'project',now});
    const hero = { id:'hero',kind:'character',title:'阿月',position:{x:0,y:-300},size:{width:360,height:260},payload:{characterId:'c1',appearance:'短发红衣',versions:[]} };
    const plan = parseCanvasStoryPlan('```json\n'+JSON.stringify({characters:[{name:'阿月',appearance:'短发红衣'}],shots:[{title:'开门',prompt:'阿月推门',characters:['阿月']},{title:'抬头',prompt:'阿月抬头',characters:['阿月']}]})+'\n```');
    const checkpoint = {id:'story',source:'阿月',chunks:['a','b'],completed:0,nodeIds:[]};
    const options = {modelId:'video-model',routeKey:'own:route',aspectRatio:'16:9',characterNodes:{阿月:hero},now};
    const first = appendCanvasStoryChunk(canvas, checkpoint, plan, options);
    assert.equal(canvas.nodes.length,0);
    assert.deepEqual(validateCanvasDocument(first), []);
    assert.equal(first.sequenceLinks.length,1);
    assert.equal(first.nodes.filter(node=>node.kind==='character').length,1);
    assert.equal(first.settings.nodeRoutes['story-0-shot-0'],'own:route');
    const next = appendCanvasStoryChunk(first,{...checkpoint,completed:1,nodeIds:['story-0-shot-0','story-0-shot-1'],lastNodeId:'story-0-shot-1'},plan,options);
    assert.deepEqual(validateCanvasDocument(next), []);
    assert.equal(next.sequenceLinks.length,3);
    assert.equal(next.nodes.filter(node=>node.kind==='character').length,1);
    assert.ok(next.nodes.find(node=>node.id==='story-1-shot-0').position.x>next.nodes.find(node=>node.id==='story-0-shot-1').position.x);
    assert.throws(()=>appendCanvasStoryChunk(first,checkpoint,plan,options),/already present/);
    assert.throws(()=>appendCanvasStoryChunk(canvas,checkpoint,plan,{...options,characterNodes:{}}),/Unknown storyboard character/);
    const aliased={...plan,shots:[{title:'Same person',prompt:'One person appears',characters:['阿月','月月']}]};
    const aliases=appendCanvasStoryChunk(canvas,checkpoint,aliased,{...options,characterNodes:{阿月:hero,月月:hero}});
    assert.equal(aliases.nodes.filter(node=>node.kind==='character').length,1);assert.equal(aliases.edges.length,1);
    assert.deepEqual(validateCanvasDocument(aliases),[]);
    const reference={id:'portrait-v1',assetId:'portrait-a1',kind:'image',uri:'nextmux.media/portrait.png',createdAt:now};
    const hydrated={...hero,payload:{...hero.payload,versions:[reference],currentVersionId:reference.id}};
    const filled=appendCanvasStoryChunk({...canvas,nodes:[hero]},checkpoint,aliased,{...options,characterNodes:{阿月:hydrated,月月:hydrated}});
    assert.equal(filled.nodes.find(node=>node.id===hero.id).payload.currentVersionId,reference.id);assert.deepEqual(hero.payload.versions,[]);
});
