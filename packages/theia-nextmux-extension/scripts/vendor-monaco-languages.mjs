#!/usr/bin/env node
// Regenerates src/browser/vendor/monaco-languages.ts from the Monarch
// grammars of the monaco-editor package (MIT, Microsoft).
//
//   npm pack monaco-editor@0.52.2 && tar -xzf monaco-editor-0.52.2.tgz
//   node scripts/vendor-monaco-languages.mjs <path-to-extracted-package>
//
// Theia's editor core ships without tokenizers; VS Code grammars normally
// arrive through plugins, which NextMux does not bundle. These Monarch
// grammars give the file drawer editor-style syntax colours offline.
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = process.argv[2];
if (!source) throw new Error('Pass the extracted monaco-editor package directory');
const esbuild = createRequire(join(root, '../../apps/desktop/package.json'))('esbuild');
const pkg = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'));
// id: [grammar folder, file extensions]
const languages = {
    typescript: ['typescript'], javascript: ['javascript'], python: ['python'], rust: ['rust'], go: ['go'], java: ['java'],
    kotlin: ['kotlin'], cpp: ['cpp'], c: ['cpp'], csharp: ['csharp'], ruby: ['ruby'], php: ['php'], swift: ['swift'],
    shell: ['shell'], powershell: ['powershell'], bat: ['bat'], html: ['html'], css: ['css'], scss: ['scss'], less: ['less'],
    yaml: ['yaml'], xml: ['xml'], markdown: ['markdown'], sql: ['sql'], graphql: ['graphql'], ini: ['ini'], dockerfile: ['dockerfile'],
    lua: ['lua'], dart: ['dart'], scala: ['scala'], r: ['r'], perl: ['perl'], 'objective-c': ['objective-c'], vb: ['vb'],
    protobuf: ['protobuf'], hcl: ['hcl'], elixir: ['elixir'], clojure: ['clojure'], fsharp: ['fsharp'], julia: ['julia'],
    solidity: ['solidity'], razor: ['razor'], handlebars: ['handlebars'], pug: ['pug'], coffeescript: ['coffee'], tcl: ['tcl'],
    scheme: ['scheme'], pascal: ['pascal'], mips: ['mips'], wgsl: ['wgsl'], systemverilog: ['systemverilog']
};
const entry = Object.entries(languages).map(([id, [folder]], index) =>
    `import * as l${index} from './esm/vs/basic-languages/${folder}/${folder}.js'; grammars[${JSON.stringify(id)}] = () => ({ conf: l${index}.conf, language: l${index}.language });`).join('\n');
const result = await esbuild.build({
    stdin: { contents: `export const grammars = {};\n${entry}`, resolveDir: source, sourcefile: 'monaco-languages-entry.js' },
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'none',
    plugins: [{ name: 'monaco-core', setup(build) {
        build.onResolve({ filter: /editor\/editor\.api\.js$/ }, () => ({ path: '@theia/monaco-editor-core', external: true }));
    } }]
});
const banner = `/* eslint-disable */
// @ts-nocheck
/*
 * Generated by scripts/vendor-monaco-languages.mjs from monaco-editor ${pkg.version}.
 * Monarch grammars: Copyright (c) Microsoft Corporation. Released under the MIT
 * license — see src/browser/vendor/MONACO-LICENSE.txt. Do not edit by hand.
 */
`;
await mkdir(join(root, 'src/browser/vendor'), { recursive: true });
await writeFile(join(root, 'src/browser/vendor/monaco-languages.ts'), banner + result.outputFiles[0].text);
await writeFile(join(root, 'src/browser/vendor/MONACO-LICENSE.txt'), await readFile(join(source, 'LICENSE'), 'utf8'));
console.log(`Wrote ${Object.keys(languages).length} grammars (${(result.outputFiles[0].text.length / 1024).toFixed(0)} KB).`);
