export function microphoneLocale(locale: NextMuxDesktopLocale): MicrophoneCatalog {
    return translations[locale];
}

function uncheckedMicrophoneText(locale: NextMuxDesktopLocale, key: MicrophoneTextKey): string {
    return translations[locale][key];
}

/** Text lookups that never throw: an unknown key or language falls back (see nextmux-copy-fallback.ts). */
export function microphoneText(locale: Parameters<typeof uncheckedMicrophoneText>[0], key: Parameters<typeof uncheckedMicrophoneText>[1], ...rest: AfterLocaleAndKey<Parameters<typeof uncheckedMicrophoneText>>): string {
    return totalCopy(locale, key, language => uncheckedMicrophoneText(language, key, ...rest));
}

