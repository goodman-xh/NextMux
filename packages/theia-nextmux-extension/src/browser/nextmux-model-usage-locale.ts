function uncheckedModelUsageText(
    locale: NextMuxDesktopLocale,
    key: UsageTextKey,
    values: Readonly<Record<string, string | number>> = {}
): string {
    return Object.entries(values).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        translations[locale]?.[key] || en[key]
    );
}

/** Text lookups that never throw: an unknown key or language falls back (see nextmux-copy-fallback.ts). */
export function modelUsageText(locale: Parameters<typeof uncheckedModelUsageText>[0], key: Parameters<typeof uncheckedModelUsageText>[1], ...rest: AfterLocaleAndKey<Parameters<typeof uncheckedModelUsageText>>): string {
    return totalCopy(locale, key, language => uncheckedModelUsageText(language, key, ...rest));
}
