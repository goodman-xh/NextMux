const TEXT: Readonly<Record<string, Readonly<Record<CanvasEdgeAuditTextKey, string>>>> = { 'zh-CN': ZH, 'zh-TW': ZH_TW, en: EN, ja: JA, ko: KO, es: ES, fr: FR, de: DE, 'pt-BR': PT_BR, ru: RU, ar: AR, hi: HI };
export function canvasEdgeAuditText(locale: string, key: CanvasEdgeAuditTextKey, values: Record<string, string | number> = {}): string {
    return totalCopy(locale, key, language => TEXT[language]?.[key]).replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
}
export function canvasEdgeReasonKey(code: string): CanvasEdgeAuditTextKey {
    if (code === 'SOURCE_PORT') return 'sourcePort';
    if (code === 'TARGET_PORT') return 'targetPort';
    if (code === 'ROLE_LIMIT') return 'roleLimit';
    if (code === 'NODE_MISSING') return 'missingEndpoint';
    if (code === 'CYCLE' || code === 'SELF_LOOP') return 'cycle';
    if (code === 'DUPLICATE_EDGE' || code === 'EDGE_ID_DUPLICATE') return 'duplicate';
    if (code === 'MODE_ROLE' || code === 'ROLE_TYPE') return 'mode';
    if (code.startsWith('GROUP_')) return 'group';
    if (code.startsWith('PIN_')) return 'binding';
    return code === 'SCAN_FAILED' ? 'failed' : 'invalid';
}
