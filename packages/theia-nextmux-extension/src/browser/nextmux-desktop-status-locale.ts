export function desktopStatusMessage(locale: NextMuxDesktopLocale, message: DomainMessage): string | undefined {
    if (!Object.prototype.hasOwnProperty.call(desktopStatusEnglish, message.code)) return undefined;
    return translations[message.code as DesktopStatusCode][locales.indexOf(locale)].replace(/\{(\w+)\}/g, (match, key: string) => String(message.params?.[key] ?? match));
}
