function uncheckedConversationStreamText(locale: NextMuxDesktopLocale, key: ConversationStreamTextKey,
    values: Readonly<Record<string, string | number>> = {}): string {
    const template = (translations[locale] || en)[key] || en[key];
    return template.replace(/\{(\w+)\}/g, (match, name: string) => name in values ? String(values[name]) : match);
}

export const conversationStreamLocales = translations;

/** Text lookups that never throw: an unknown key or language falls back (see nextmux-copy-fallback.ts). */
export function conversationStreamText(locale: Parameters<typeof uncheckedConversationStreamText>[0], key: Parameters<typeof uncheckedConversationStreamText>[1], ...rest: AfterLocaleAndKey<Parameters<typeof uncheckedConversationStreamText>>): string {
    return totalCopy(locale, key, language => uncheckedConversationStreamText(language, key, ...rest));
}
