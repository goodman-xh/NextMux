/** Exact fixed labels and bounded duration displays only; story titles and dialogue remain untouched. */
export function reviewedMediaSurfaceText(locale: NextMuxDesktopLocale, value: string): string | undefined {
    const index = MEDIA_SURFACE_LOCALES.indexOf(locale);
    if (index < 0) return undefined;
    const trimmed = value.trim();
    const row = MEDIA_SURFACE_REVIEWED[trimmed];
    let text = row?.[index];
    if (text === undefined) {
        const duration = /^(\d+(?:\.\d+)?) 秒( · \d+ × \d+)?$/.exec(trimmed);
        const audio = /^(\d+(?:\.\d+)?) 秒 · 音频将作为独立轨道保存$/.exec(trimmed);
        if (duration) text = `${duration[1]} ${MEDIA_SURFACE_REVIEWED['秒'][index]}${duration[2] ?? ''}`;
        else if (audio) text = `${audio[1]} ${MEDIA_SURFACE_REVIEWED['秒'][index]} · ${MEDIA_SURFACE_REVIEWED['音频将作为独立轨道保存'][index]}`;
    }
    return text === undefined ? undefined : value.slice(0, value.indexOf(trimmed)) + text + value.slice(value.indexOf(trimmed) + trimmed.length);
}
