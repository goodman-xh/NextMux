export function componentDomainMessage(locale: NextMuxDesktopLocale, message: DomainMessage): string | undefined {
    if (message.code === 'TERMINAL_RUNTIME_UNSUPPORTED') return terminalSurfaceText(locale, 'unsupportedRuntime');
    const row = messages[message.code as keyof typeof messages];
    if (!row) return undefined;
    return row[locale].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (token, key: string) => {
        const value = message.params?.[key];
        return typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean' ? String(value) : token;
    });
}
