type MessageKey = keyof typeof messages.en;
const aliases: Readonly<Record<string, MessageKey>> = {
    placeholder: 'unknown', field: 'unknown', expression_action: 'unknown', expression_signal: 'unknown',
    package_size: 'package_limit', package_files: 'package_limit', package_file_size: 'package_limit',
    package_path: 'package_path', package_link: 'package_path', package_unexpected_file: 'package_path', package_not_png: 'package_path', package_duplicate: 'package_path',
    package_identity_mismatch: 'identity', package_manifest_missing: 'expected'
};

export function appPluginDiagnosticText(locale: NextMuxDesktopLocale, diagnostic: AppPluginDiagnostic): string {
    const code = diagnostic.code.replace(/^plugin\./, '');
    const key = aliases[code] || (Object.prototype.hasOwnProperty.call(messages.en, code) ? code as MessageKey : code.startsWith('package_') ? 'package' : 'invalid');
    const params: AppPluginDiagnostic['params'] = code === 'package_manifest_missing' ? { ...diagnostic.params, expected: 'plugin.json' } : diagnostic.params;
    const body = messages[locale][key].replace(/\{(\w+)\}/g, (_all, name: string) => String(params[name] ?? ''));
    return diagnostic.path ? `${diagnostic.path}: ${body}` : body;
}

/** Older hosts can still send string errors; they remain diagnostic data, never user-facing prose. */
export function appPluginDiagnostics(locale: NextMuxDesktopLocale, value: { readonly diagnostics?: readonly AppPluginDiagnostic[]; readonly errors?: readonly string[]; readonly failures?: readonly string[] }): readonly string[] {
    if (value.diagnostics?.length) return value.diagnostics.map(item => appPluginDiagnosticText(locale, item));
    return (value.errors || value.failures || []).map(() => messages[locale].invalid);
}

export function appPluginReplayName(locale: NextMuxDesktopLocale): string { return messages[locale].replay_name; }
