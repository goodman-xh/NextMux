function uncheckedMediaRuntimeText(
    locale: NextMuxDesktopLocale,
    key: MediaRuntimeTextKey,
    values: Readonly<Record<string, string | number>> = {}
): string {
    return translations[locale][key].replace(/\{([a-z]+)\}/gi, (_match, name: string) => String(values[name] ?? ''));
}

/** Text lookups that never throw: an unknown key or language falls back (see nextmux-copy-fallback.ts). */
export function mediaRuntimeText(locale: Parameters<typeof uncheckedMediaRuntimeText>[0], key: Parameters<typeof uncheckedMediaRuntimeText>[1], ...rest: AfterLocaleAndKey<Parameters<typeof uncheckedMediaRuntimeText>>): string {
    return totalCopy(locale, key, language => uncheckedMediaRuntimeText(language, key, ...rest));
}
