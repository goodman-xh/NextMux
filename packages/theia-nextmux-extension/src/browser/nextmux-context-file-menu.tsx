/** Uses the file-tab popup's existing classes and behavior; no navigator selection is consulted. */
export function ContextFileMenu(props: {
    readonly locale: NextMuxDesktopLocale; readonly x: number; readonly y: number;
    readonly items: readonly (ContextFileActionItem & { readonly label: string })[];
    readonly onAction: (action: ContextFileAction) => void;
    readonly onDismiss: (restoreFocus?: boolean) => void;
}): React.ReactElement {
    const menu = React.useRef<HTMLDivElement>(null);
    const [position, setPosition] = React.useState({ left: props.x, top: props.y });
    const ready = props.items.some(item => !item.disabled);
    React.useLayoutEffect(() => {
        const element = menu.current;
        if (!element) return;
        const rect = element.getBoundingClientRect();
        setPosition({ left: Math.max(8, Math.min(props.x, window.innerWidth - rect.width - 8)),
            top: Math.max(8, Math.min(props.y, window.innerHeight - rect.height - 8)) });
        (element.querySelector<HTMLButtonElement>('button:not(:disabled)') || element).focus();
    }, [props.x, props.y, ready, props.locale]);
    return <>
        <div className='nmx-file-tab-menu-backdrop' onMouseDown={event => { event.stopPropagation(); props.onDismiss(); }}
            onContextMenu={event => { event.preventDefault(); event.stopPropagation(); props.onDismiss(); }} />
        <div ref={menu} className='nmx-file-tab-menu' role='menu' tabIndex={-1} data-nmx-literal
            aria-label={contextFileText(props.locale, 'actions')}
            style={{ ...position, maxHeight: 'calc(100vh - 16px)', maxWidth: 'calc(100vw - 16px)', overflowY: 'auto' }}
            onMouseDown={event => event.stopPropagation()} onContextMenu={event => { event.preventDefault(); event.stopPropagation(); }}
            onKeyDown={event => {
                if (event.key === 'Escape' || event.key === 'Tab') {
                    if (event.key === 'Escape') event.preventDefault();
                    event.stopPropagation(); props.onDismiss(event.key === 'Escape'); return;
                }
                if (!['ArrowDown', 'ArrowUp', 'Home', 'End'].includes(event.key)) return;
                event.preventDefault(); event.stopPropagation();
                const items = [...(menu.current?.querySelectorAll<HTMLButtonElement>('button:not(:disabled)') || [])];
                if (!items.length) return;
                const index = items.indexOf(document.activeElement as HTMLButtonElement);
                const next = event.key === 'Home' ? 0 : event.key === 'End' ? items.length - 1
                    : event.key === 'ArrowDown' ? (index + 1) % items.length : (index <= 0 ? items.length : index) - 1;
                items[next]?.focus();
            }}>
            {props.items.map(item => <React.Fragment key={item.id}>
                {item.separatorBefore && <hr />}
                <button type='button' role='menuitem' title={item.label} disabled={item.disabled}
                    style={item.disabled ? { opacity: .5 } : undefined}
                    onClick={() => { props.onDismiss(); props.onAction(item.id); }}>
                    <span style={{ overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>{item.label}</span>
                </button>
            </React.Fragment>)}
        </div>
    </>;
}
